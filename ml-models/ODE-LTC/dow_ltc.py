import os
import pandas as pd
import numpy as np
from tensorflow import keras
import tensorflow as tf
import time
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.preprocessing import LabelEncoder
import tensorflow as tf
from tensorflow import keras
from ncps import wirings
from ncps.keras import LTC, CfC
import datetime as dt
from sklearn.preprocessing import MinMaxScaler
from sklearn.model_selection import train_test_split

"""## **Load Dataset**"""

#============================================================================================
dataset = pd.read_csv('filename.csv') # Dataset
#============================================================================================

"""## Scaling (Minmax/StdScaler)"""

bot = dataset['bot']

dataset = dataset.drop('bot', axis=1)

# Apply scaling
columns_to_scale = ['SubmitTime', 'RTT', 'InvocationDelay', 'ResponseDelay',
       'FunctionDuration', 'ActiveFunctionsAtRequest',
       'ActiveFunctionsAtResponse', 'maxcpu', 'avgcpu', 'p95maxcpu', 'vmcorecountbucket', 'vmmemorybucket']

#Initialize Scaler
scaler = MinMaxScaler()

# Fit and transform the specific columns
dataset[dataset.columns] = scaler.fit_transform(dataset[dataset.columns])

#Splitting data into train and test sets
train_x, test_x, train_y, test_y = train_test_split(dataset, bot, test_size=0.2, shuffle=False)
train_y = train_y.values
test_y = test_y.values

N_train = train_x.shape[0]
train_x = np.expand_dims(train_x, axis=0).astype(np.float32)
train_y = train_y.reshape([1, N_train, 1]).astype(np.float32)

N_test = test_x.shape[0]
test_x = np.expand_dims(test_x, axis=0).astype(np.float32)
test_y = test_y.reshape([1, N_test, 1]).astype(np.float32)

"""## LTC"""

wiring = wirings.AutoNCP(9, 3)
model = keras.models.Sequential(
    [
        keras.layers.InputLayer(input_shape=(None,train_x.shape[2])),
        #keras.layers.Dense(9, activation="tanh"),
        #keras.layers.Dense(3, activation="tanh"),
        LTC(wiring, return_sequences=True),
        #keras.layers.Dense(9, activation="tanh"),
        keras.layers.Dense(1, activation="sigmoid")
    ]
)
model.compile(
    optimizer=keras.optimizers.Adam(0.001), loss='binary_crossentropy'
)

model.summary()

#Neural Structure defined by NCP

sns.set_style("white")
plt.figure(figsize=(6, 4))
legend_handles = wiring.draw_graph(draw_labels=True, neuron_colors={"command": "tab:cyan"})
plt.legend(handles=legend_handles, loc="upper center", bbox_to_anchor=(1, 1))
sns.despine(left=True, bottom=True)
plt.tight_layout()
plt.show()

hist = model.fit(x=train_x, y=train_y, batch_size=1, epochs=100, verbose=2, shuffle=False)

# Plot The Training loss
sns.set()
plt.figure(figsize=(6, 4))
plt.plot(hist.history["loss"], label="Training loss")
plt.legend(loc="upper right")
plt.xlabel("Training steps")
plt.show()

# Train Prediction
sns.set()
prediction_train = model(train_x).numpy()
plt.figure(figsize=(6, 4))
plt.plot(train_y[0, :, 0], label="Target output")
plt.plot(prediction_train[0, :, 0], label="LTC")
plt.title("After training Train")
plt.legend(loc="upper right")
plt.show()

# Test Prediction
sns.set()
# Record the start time
start_test_time = time.time()

prediction_test = model(test_x).numpy()

# Record the end time
end_test_time = time.time()

plt.figure(figsize=(6, 4))
plt.plot(test_y[0, :, 0], label="Target output")
plt.plot(prediction_test[0, :, 0], label="LTC")
plt.title("After training Test")
plt.legend(loc="upper right")
plt.show()

#Calculating metrics
from sklearn.metrics import accuracy_score,precision_score,recall_score,f1_score
prediction_train = np.where(prediction_train[0, :, 0] > 0.5, 1, 0).astype(np.float32)
prediction_test = np.where(prediction_test[0, :, 0] > 0.5, 1, 0).astype(np.float32)

#Training Metrics
accuracy_train = accuracy_score(train_y[0, : ,0], prediction_train)
precision_train = precision_score(train_y[0, : ,0], prediction_train)
recall_train = recall_score(train_y[0, : ,0], prediction_train)
f1_train = f1_score(train_y[0, : ,0], prediction_train)
print('Train Score: \n{:.5f} Accuracy \n{:.5f} Precision \n{:.5f} recall \n{:.5f} F1'.format(accuracy_train,precision_train,recall_train,f1_train))

#Testing Metrics
accuracy_test = accuracy_score(test_y[0, : ,0], prediction_test)
precision_test = precision_score(test_y[0, : ,0], prediction_test)
recall_test = recall_score(test_y[0, : ,0], prediction_test)
f1_test = f1_score(test_y[0, : ,0], prediction_test)
print('\nTest Score: \n{:.5f} Accuracy \n{:.5f} Precision \n{:.5f} recall \n{:.5f} F1'.format(accuracy_test,precision_test,recall_test,f1_test))